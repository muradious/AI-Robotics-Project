"""
export_policy.py -- bridge from SIMULATION to the REAL ROBOT
=============================================================

Run this after you are happy with your simulation:

    python hardware/export_policy.py                      # simple maze, Q-Learning policy
    python hardware/export_policy.py --layout complex
    python hardware/export_policy.py --source vi          # use the Value Iteration policy instead

It writes  hardware/esp32_rover/map.h  containing
    * the maze (obstacles, start, goal)      -> becomes the robot's initial map
    * the policy learned in simulation       -> the first moves the real robot makes

Then open hardware/esp32_rover/esp32_rover.ino in the Arduino IDE and upload it.

(The file is only C source text -- you can read it to see exactly what the robot receives.)
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

import agents  # noqa: E402
import config as C  # noqa: E402
import dp  # noqa: E402
from gridworld import LAYOUTS, GridWorld  # noqa: E402


def build_header(layout, source, episodes=1500, seed=0):
    env = GridWorld(layout)                                       # deterministic world
    if source == "vi":
        policy = dp.value_iteration(env)["policy"]
        origin = "Value Iteration"
    else:
        Q, _ = agents.q_learning(env, episodes=episodes, seed=seed,
                                 eps_fn=agents.make_epsilon_schedule("decay", 1.0, 0.02, 0.995))
        policy = agents.greedy_policy_from_q(env, Q)
        origin = f"Q-Learning ({episodes} episodes, seed {seed})"

    # Check the exported policy really reaches the goal before putting it on a robot.
    s, steps = env.start, 0
    while s != env.goal and steps < 200:
        s = env.P[s][int(policy[s])][0][1]
        steps += 1
    ok = s == env.goal
    print(f"policy from {origin}: reaches goal = {ok} in {steps} steps")
    if not ok:
        print("WARNING: this policy does not reach the goal -- train longer or use --source vi")

    rows = LAYOUTS[layout]
    n = env.n_rows
    lines = [
        f"// map.h -- GENERATED by hardware/export_policy.py -- do not edit by hand.",
        f"// layout = {layout}, policy from {origin}",
        "#pragma once",
        "#include <stdint.h>",
        f"#define GRID_N {n}",
        f"#define START_R {env.s_to_rc(env.start)[0]}",
        f"#define START_C {env.s_to_rc(env.start)[1]}",
        f"#define GOAL_R_CELL {env.s_to_rc(env.goal)[0]}",
        f"#define GOAL_C_CELL {env.s_to_rc(env.goal)[1]}",
        "// '#' = obstacle, '.' = free, 'S' = start, 'G' = goal   (row 0 is the top row)",
        f"static const char MAP_ROWS[GRID_N][GRID_N + 1] = {{",
        *[f'  "{row}",' for row in rows],
        "};",
        "// Action per cell: 0=UP 1=RIGHT 2=DOWN 3=LEFT (the policy learned in simulation)",
        "static const uint8_t PLANNED_POLICY[GRID_N][GRID_N] = {",
    ]
    for r in range(n):
        vals = ", ".join(str(int(policy[env.rc_to_s(r, c)])) for c in range(n))
        lines.append("  {" + vals + "},")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--layout", default="simple", choices=list(LAYOUTS))
    ap.add_argument("--source", default="q", choices=["q", "vi"])
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "esp32_rover", "map.h"))
    args = ap.parse_args()
    text = build_header(args.layout, args.source)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", args.out)
